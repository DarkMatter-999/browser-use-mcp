import { generateKeyPairSync } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deriveExtensionId } from "../src/shared/extension-id";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const manifestPath = join(root, "packages", "extension", "public", "manifest.json");
const idPath = join(root, "packages", "protocol", "src", "extension-id.ts");

const manifest = JSON.parse(await readFile(manifestPath, "utf8")) as Record<string, unknown>;
if (manifest.key !== undefined && !process.argv.includes("--force")) {
  console.error(
    "manifest.json already has a key; pass --force to replace it (this changes the extension ID).",
  );
  process.exit(1);
}

const { publicKey, privateKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
const spki = publicKey.export({ type: "spki", format: "der" }).toString("base64");
const id = await deriveExtensionId(spki);

await mkdir(join(root, ".keys"), { recursive: true });
await writeFile(
  join(root, ".keys", "extension-key.pem"),
  privateKey.export({ type: "pkcs8", format: "pem" }),
  { mode: 0o600 },
);
manifest.key = spki;
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(
  idPath,
  `// Generated by packages/extension/scripts/generate-key.ts. Do not edit by hand.\nexport const EXTENSION_ID = "${id}";\n`,
);
console.log(`Extension ID: ${id}`);
